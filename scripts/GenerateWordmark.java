import java.awt.Font;
import java.awt.font.FontRenderContext;
import java.awt.font.GlyphVector;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.io.File;
import java.util.Locale;

/**
 * Generates the Kumiho launch wordmark as an Android vector drawable.
 *
 * <pre>
 * java scripts/GenerateWordmark.java Roboto-SemiBold.ttf Kumiho 0.06 \
 *   &gt; android/app/src/main/res/drawable/ic_wordmark.xml
 * </pre>
 *
 * The outline is taken from the real font at 100 px so the vector is crisp at
 * every density: no raster, no new runtime font. The font file is a build-time
 * input only and is never committed.
 */
public final class GenerateWordmark {

    private static final float SIZE = 100f;

    public static void main(String[] args) throws Exception {
        if (args.length != 3) {
            System.err.println("usage: GenerateWordmark <font.ttf> <text> <tracking-em>");
            System.exit(2);
        }
        Font font = Font.createFont(Font.TRUETYPE_FONT, new File(args[0])).deriveFont(SIZE);
        String text = args[1];
        float tracking = Float.parseFloat(args[2]) * SIZE;

        FontRenderContext frc = new FontRenderContext(null, true, true);
        GlyphVector glyphs = font.createGlyphVector(frc, text);
        for (int i = 0; i < glyphs.getNumGlyphs(); i++) {
            double x = glyphs.getGlyphPosition(i).getX() + i * tracking;
            glyphs.setGlyphPosition(i, new java.awt.geom.Point2D.Float((float) x, 0f));
        }

        Rectangle2D bounds = glyphs.getVisualBounds();
        double width = bounds.getWidth();
        double height = bounds.getHeight();

        StringBuilder data = new StringBuilder();
        PathIterator it = glyphs.getOutline().getPathIterator(null);
        double[] p = new double[6];
        while (!it.isDone()) {
            int type = it.currentSegment(p);
            switch (type) {
                case PathIterator.SEG_MOVETO ->
                        data.append('M').append(n(p[0] - bounds.getMinX())).append(' ')
                                .append(n(p[1] - bounds.getMinY()));
                case PathIterator.SEG_LINETO ->
                        data.append("L").append(n(p[0] - bounds.getMinX())).append(' ')
                                .append(n(p[1] - bounds.getMinY()));
                case PathIterator.SEG_QUADTO ->
                        data.append("Q").append(n(p[0] - bounds.getMinX())).append(' ')
                                .append(n(p[1] - bounds.getMinY())).append(' ')
                                .append(n(p[2] - bounds.getMinX())).append(' ')
                                .append(n(p[3] - bounds.getMinY()));
                case PathIterator.SEG_CUBICTO ->
                        data.append("C").append(n(p[0] - bounds.getMinX())).append(' ')
                                .append(n(p[1] - bounds.getMinY())).append(' ')
                                .append(n(p[2] - bounds.getMinX())).append(' ')
                                .append(n(p[3] - bounds.getMinY())).append(' ')
                                .append(n(p[4] - bounds.getMinX())).append(' ')
                                .append(n(p[5] - bounds.getMinY()));
                case PathIterator.SEG_CLOSE -> data.append('Z');
                default -> throw new IllegalStateException("unexpected segment " + type);
            }
            it.next();
        }

        StringBuilder out = new StringBuilder();
        out.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n");
        out.append("<!--\n");
        out.append("  Kumiho wordmark: Roboto SemiBold, 0.06 em tracking, outlined to\n");
        out.append("  vectors so it stays crisp at every density. Launch screen only.\n");
        out.append("  Font: Roboto SemiBold, https://fonts.gstatic.com/s/roboto/v51/\n");
        out.append("  KFOMCnqEu92Fr1ME7kSn66aGLdTylUAMQXC89YmC2DPNWuYaalmUiA8.ttf\n");
        out.append("  SHA-256 868599499d20ee12589f2b7a314443d5bbe86d88e95eb2bf89b6f2fb9cb0e3c5\n");
        out.append("  License: Apache License 2.0, Copyright The Android Open Source Project.\n");
        out.append("  Generated by scripts/GenerateWordmark.java; do not hand-edit.\n");
        out.append("-->\n");
        out.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        out.append("    android:width=\"128dp\"\n");
        out.append("    android:height=\"28dp\"\n");
        out.append("    android:viewportWidth=\"").append(n(width)).append("\"\n");
        out.append("    android:viewportHeight=\"").append(n(height)).append("\">\n");
        out.append("    <path\n");
        out.append("        android:fillColor=\"@color/kumiho_on_surface\"\n");
        out.append("        android:pathData=\"").append(data).append("\" />\n");
        out.append("</vector>\n");
        System.out.print(out);
    }

    private static String n(double value) {
        double rounded = Math.round(value * 100.0) / 100.0;
        if (rounded == -0.0) {
            rounded = 0.0;
        }
        return String.format(Locale.ROOT, "%.2f", rounded);
    }

    private GenerateWordmark() {
    }
}
