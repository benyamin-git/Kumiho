#!/usr/bin/env bash
#
# Generate the Android 4:3 flag drawables and their explicit resource map from
# the pinned flag-icons source in the GUI tree.
#
# The GUI serves the source SVGs directly; Android gets 192x144 lossless WebP
# files under res/drawable-nodpi. The map is generated so R8 sees a direct
# reference to every drawable; there is no reflection or runtime SVG decoder.
#
#   scripts/flags/generate-android-flags.sh
#
# Environment overrides:
#   FLAG_ICONS_DIR       source SVG directory (default internal/gui/web/static/flags/4x3)
#   ANDROID_FLAGS_DIR    output WebP directory (default android/app/src/main/res/drawable-nodpi)
#   COUNTRY_FLAGS_KT     generated Kotlin map (default .../CountryFlagsResources.kt)
#   FLAG_ICONS_EXPECTED  expected source count (default 249 for flag-icons 7.6.0)
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source_dir="${FLAG_ICONS_DIR:-$repo_root/internal/gui/web/static/flags/4x3}"
out_dir="${ANDROID_FLAGS_DIR:-$repo_root/android/app/src/main/res/drawable-nodpi}"
map_file="${COUNTRY_FLAGS_KT:-$repo_root/android/app/src/main/java/dev/benyamin/kumiho/ui/locations/CountryFlagsResources.kt}"
expected="${FLAG_ICONS_EXPECTED:-249}"

for tool in ffmpeg ffprobe; do
	command -v "$tool" >/dev/null 2>&1 || {
		echo "generate-android-flags: $tool not found on PATH" >&2
		exit 1
	}
done
if ! ffmpeg -hide_banner -decoders 2>/dev/null | grep -F 'librsvg' >/dev/null; then
	echo "generate-android-flags: ffmpeg lacks the librsvg SVG decoder" >&2
	exit 1
fi
[ -d "$source_dir" ] || {
	echo "generate-android-flags: source directory not found: $source_dir" >&2
	exit 1
}

tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT

mapfile -t sources < <(find "$source_dir" -maxdepth 1 -type f -name '*.svg' -printf '%f\n' | LC_ALL=C sort)
[ "${#sources[@]}" -eq "$expected" ] || {
	echo "generate-android-flags: found ${#sources[@]} SVG files, expected $expected" >&2
	exit 1
}

for name in "${sources[@]}"; do
	[[ "$name" =~ ^[a-z]{2}\.svg$ ]] || {
		echo "generate-android-flags: non two-letter source: $name" >&2
		exit 1
	}
done

mkdir -p "$out_dir" "$(dirname "$map_file")"
rm -f "$out_dir"/flag_*.webp

{
	printf '%s\n' '// Code generated by scripts/flags/generate-android-flags.sh; DO NOT EDIT.'
	printf '%s\n\n' 'package dev.benyamin.kumiho.ui.locations'
	printf '%s\n\n' 'import dev.benyamin.kumiho.R'
	printf '%s\n' 'internal val COUNTRY_FLAG_RESOURCES: Map<String, Int> = mapOf('
} >"$tmp_dir/CountryFlagsResources.kt"

for name in "${sources[@]}"; do
	code="${name%.svg}"
	out="$tmp_dir/flag_$code.webp"
	ffmpeg -nostdin -loglevel error -y -i "$source_dir/$name" \
		-map_metadata -1 -fflags +bitexact \
		-vf 'scale=192:144:flags=lanczos' -frames:v 1 \
		-c:v libwebp -lossless 1 -compression_level 6 "$out"
	probe="$(ffprobe -v error -select_streams v:0 \
		-show_entries stream=width,height,codec_name -of csv=p=0 "$out")"
	[ "$probe" = 'webp,192,144' ] || {
		echo "generate-android-flags: $name produced '$probe', expected webp,192,144" >&2
		exit 1
	}
	mv "$out" "$out_dir/flag_$code.webp"
	printf '    "%s" to R.drawable.flag_%s,\n' "$code" "$code" >>"$tmp_dir/CountryFlagsResources.kt"
done

printf '%s\n' ')' >>"$tmp_dir/CountryFlagsResources.kt"
mv "$tmp_dir/CountryFlagsResources.kt" "$map_file"

echo "generate-android-flags: ${#sources[@]} flags -> $out_dir"
echo "generate-android-flags: resource map -> $map_file"
